const dicts: Record<Lang, Partial<Record<MsgKey, string>>> = { en, sq, de };

export function translate(lang: Lang, key: MsgKey): string {
  return dicts[lang]?.[key] ?? en[key];
}

/** Food names: use the localised name when we have one. */
export function foodName(food: { name: string; localNames?: Record<string, string> | null }, lang: Lang) {
  if (lang === "en") return food.name;
  return food.localNames?.[lang] ?? food.name;
}
